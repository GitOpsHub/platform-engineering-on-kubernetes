package v1alpha1

import (
	"fmt"
	"regexp"
	"strings"

	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
)

// dnsLabelRegexp is the strict RFC 1123 DNS label used for namespace names.
var dnsLabelRegexp = regexp.MustCompile(`^[a-z0-9]([-a-z0-9]*[a-z0-9])?$`)

// reservedNamespaces can never be provisioned by a Tenant.
var reservedNamespaces = []string{"default", "platform-system"}

// reservedNamespacePrefixes can never be provisioned by a Tenant.
var reservedNamespacePrefixes = []string{"kube-"}

// reservedKeyPrefixes may not be set by users on Tenant labels/annotations
// because they would be copied onto (or could override) operator-owned or
// Kubernetes-owned metadata of generated namespaces.
var reservedKeyPrefixes = []string{
	"platform.mycompany.io/",
	"pod-security.kubernetes.io/",
	"kubernetes.io/",
	"k8s.io/",
}

// kubectlKeyPrefix marks kubectl bookkeeping (e.g. last-applied-configuration).
// Users may set these on a Tenant, but they are never copied to namespaces.
const kubectlKeyPrefix = "kubectl.kubernetes.io/"

// IsReservedNamespace reports whether name may not be used for a tenant namespace.
// operatorNamespace is the namespace the operator itself runs in.
func IsReservedNamespace(name, operatorNamespace string) bool {
	if name == "" {
		return true
	}
	if operatorNamespace != "" && name == operatorNamespace {
		return true
	}
	for _, r := range reservedNamespaces {
		if name == r {
			return true
		}
	}
	for _, p := range reservedNamespacePrefixes {
		if strings.HasPrefix(name, p) {
			return true
		}
	}
	return false
}

// ValidateNamespaceName checks a tenant namespace name against the strict DNS
// label rule, the length limit and the reserved names/prefixes.
func ValidateNamespaceName(name, operatorNamespace string) error {
	if len(name) > 63 {
		return fmt.Errorf("namespace %q must be at most 63 characters", name)
	}
	if !dnsLabelRegexp.MatchString(name) {
		return fmt.Errorf("namespace %q must be a DNS-1123 label (lowercase alphanumerics and '-', starting and ending with an alphanumeric)", name)
	}
	if IsReservedNamespace(name, operatorNamespace) {
		return fmt.Errorf("namespace %q is reserved", name)
	}
	return nil
}

// IsReservedKey reports whether a label or annotation key uses a prefix that
// users may not set on a Tenant.
func IsReservedKey(key string) bool {
	for _, p := range reservedKeyPrefixes {
		if strings.HasPrefix(key, p) {
			return true
		}
	}
	return false
}

// FilterUserMetadata returns a copy of in without reserved keys and kubectl
// bookkeeping. The controller uses it so user metadata can never override
// operator-owned keys.
func FilterUserMetadata(in map[string]string) map[string]string {
	out := make(map[string]string, len(in))
	for k, v := range in {
		if !IsReservedKey(k) && !strings.HasPrefix(k, kubectlKeyPrefix) {
			out[k] = v
		}
	}
	return out
}

// IsTenantManaged reports whether obj carries the labels that mark it as
// generated by this operator for the tenant named tenantName. Labels alone are
// not proof of ownership: they are only used to adopt a namespace, and the
// adopted object then receives a controller reference.
func IsTenantManaged(obj metav1.Object, tenantName string) bool {
	l := obj.GetLabels()
	return l[LabelManagedBy] == ManagedByValue && l[LabelTenant] == tenantName
}

// CanAdoptNamespace reports whether the operator may take over an existing
// namespace for tenant. Adoption requires the managed-by/tenant labels, or a
// controller reference already pointing at the tenant.
func CanAdoptNamespace(obj metav1.Object, tenant metav1.Object) bool {
	return IsTenantManaged(obj, tenant.GetName()) || metav1.IsControlledBy(obj, tenant)
}
